// Generates the app's logo components and favicon from the brand files in
// docs/design/brand/logo/, which are the real logos (spec 32).
// Usage: pnpm brand   (writes; then renders favicon.ico and apple-icon.png)
// The test in src/components/brand/brand.test.ts calls generate() and fails
// if what's on disk has drifted from the brand files.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const LOGO_DIR = "docs/design/brand/logo";

/** Brand hex → theme value for tone "auto". */
const AUTO = {
  "#5a32d6": "var(--violet)",
  "#f6c453": "var(--marigold)",
  "#08090a": "currentColor",
};

const LOGO_TONES = {
  onDark: "jubilee-logo-on-dark.svg",
  onViolet: "jubilee-logo-on-violet.svg",
  monoInk: "jubilee-logo-mono-ink.svg",
  monoWhite: "jubilee-logo-mono-white.svg",
};
const ICON_TONES = { onDark: "jubilee-icon-on-dark.svg" };

function read(root, file) {
  return fs.readFileSync(path.join(root, LOGO_DIR, file), "utf8");
}

const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];

/** The drawn shapes (path or circle) of a flat SVG, in order. */
function shapes(svg) {
  return [...svg.matchAll(/<(path|circle)\b[^>]*\/>/g)].map(([tag, kind]) => ({
    kind,
    d: attr(tag, "d"),
    cx: attr(tag, "cx"),
    cy: attr(tag, "cy"),
    r: attr(tag, "r"),
    fill: attr(tag, "fill")?.toLowerCase(),
    opacity: attr(tag, "fill-opacity"),
  }));
}

function viewBox(svg) {
  const vb = svg.match(/viewBox="([^"]+)"/)[1];
  const [, , w, h] = vb.split(/\s+/).map(Number);
  return { vb, w, h };
}

/** One brand drawing, with the fill of each shape for every tone. */
function drawing(root, base, tones) {
  const svg = read(root, base);
  const geometry = shapes(svg);
  const fills = {
    auto: geometry.map((s) => {
      const v = AUTO[s.fill];
      if (!v) throw new Error(`${base}: no theme colour for ${s.fill}`);
      return v;
    }),
  };
  for (const [tone, file] of Object.entries(tones)) {
    const other = shapes(read(root, file));
    if (other.length !== geometry.length)
      throw new Error(`${file}: shapes differ from ${base}`);
    other.forEach((s, i) => {
      const g = geometry[i];
      if (s.d !== g.d || s.cx !== g.cx || s.cy !== g.cy || s.r !== g.r)
        throw new Error(`${file}: shape ${i} differs from ${base}`);
    });
    fills[tone] = other.map((s) => (s.fill === "white" ? "#ffffff" : s.fill));
  }
  return { ...viewBox(svg), geometry, fills };
}

function shapeJsx(s, i) {
  const fill = `fill={FILLS[tone][${i}]}`;
  const opacity = s.opacity ? ` fillOpacity={${Number(s.opacity)}}` : "";
  return s.kind === "path"
    ? `      <path d="${s.d}" ${fill}${opacity} />`
    : `      <circle cx={${s.cx}} cy={${s.cy}} r={${s.r}} ${fill}${opacity} />`;
}

function component({ name, source, doc, height, d }) {
  const tones = Object.keys(d.fills);
  return `// Generated by scripts/brand.mjs from ${LOGO_DIR}/${source}.
// Do not edit: change the brand file and run \`pnpm brand\` (spec 32).

${doc}
const FILLS = ${JSON.stringify(d.fills, null, 2)} as const;

export type ${name}Tone = ${tones.map((t) => JSON.stringify(t)).join(" | ")};

export function ${name}({
  height = ${height},
  tone = "auto",
  className,
}: {
  height?: number;
  tone?: ${name}Tone;
  className?: string;
}) {
  return (
    <svg
      viewBox="${d.vb}"
      height={height}
      width={(height * ${d.w}) / ${d.h}}
      aria-hidden="true"
      focusable="false"
      className={className}
    >
${d.geometry.map(shapeJsx).join("\n")}
    </svg>
  );
}
`;
}

/** Every generated file, path relative to root → contents. */
export function generate(root) {
  return {
    "src/components/brand/jubilee-logo.tsx": component({
      name: "JubileeLogo",
      source: "jubilee-logo*.svg",
      height: 24,
      doc: `/**
 * The Jubilee logo (decisions 0010, 0019): the steps and the wordmark.
 * "auto" follows the theme: violet and marigold tokens, the wordmark in
 * currentColor. The other tones are the brand files exactly.
 */`,
      d: drawing(root, "jubilee-logo.svg", LOGO_TONES),
    }),
    "src/components/brand/jubilee-icon.tsx": component({
      name: "JubileeIcon",
      source: "jubilee-icon*.svg",
      height: 40,
      doc: `/**
 * The Jubilee icon, "the steps" (decision 0019). "auto" follows the theme's
 * violet and marigold tokens. Decorative where the page names Jubilee.
 */`,
      d: drawing(root, "jubilee-icon.svg", ICON_TONES),
    }),
    "src/app/icon.svg": read(root, "jubilee-favicon.svg"),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = path.resolve(process.argv[2] ?? ".");
  for (const [file, contents] of Object.entries(generate(root)))
    fs.writeFileSync(path.join(root, file), contents);
  console.log("brand: components and icon.svg written");
}
